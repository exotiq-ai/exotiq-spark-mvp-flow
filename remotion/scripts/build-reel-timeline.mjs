import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const audioDir = path.resolve(__dirname, "../public/audio/reels");
const durations = JSON.parse(fs.readFileSync(path.join(audioDir, "durations.json"), "utf8"));

const FPS = 30;
const LEAD_IN_FRAMES = 15; // 0.5s hook before Rari speaks
const GAP_FRAMES = 15; // 0.5s between body lines
const PAYOFF_PAD_FRAMES = 30; // 1s visual hold after payoff line
const END_CARD_FRAMES = 150; // 5s
const CTA_GAP_FRAMES = 30; // 1s pause before CTA for visual beat
const VISUAL_BEAT_FRAMES = 90; // 3s extra UI showcase before CTA

const timelines = [];

for (const reel of durations) {
  const lines = reel.lines;
  // Last line is the CTA for all reels
  const ctaLine = lines[lines.length - 1];
  const bodyLines = lines.slice(0, -1);

  let cursor = LEAD_IN_FRAMES;
  const lineSegments = [];

  for (let i = 0; i < bodyLines.length; i++) {
    const line = bodyLines[i];
    const durFrames = Math.round(line.duration * FPS);
    lineSegments.push({ ...line, from: cursor, duration: durFrames });
    cursor += durFrames + GAP_FRAMES;
  }

  // Payoff text appears with the last body line (or after it? plan says under line 5)
  // We'll set payoff to start at the last body line start and hold through CTA + pad.
  const lastBody = lineSegments[lineSegments.length - 1];
  const payoffStart = lastBody.from;

  // CTA after a visual beat following last body line
  const ctaFrom = cursor - GAP_FRAMES + CTA_GAP_FRAMES + VISUAL_BEAT_FRAMES;
  const ctaDur = Math.round(ctaLine.duration * FPS);
  const ctaSegment = { ...ctaLine, from: ctaFrom, duration: ctaDur };

  const endCardFrom = ctaFrom + ctaDur + PAYOFF_PAD_FRAMES;
  const totalFrames = endCardFrom + END_CARD_FRAMES;

  timelines.push({
    id: reel.id,
    fps: FPS,
    width: 1080,
    height: 1920,
    totalFrames,
    totalSeconds: totalFrames / FPS,
    leadIn: LEAD_IN_FRAMES,
    lines: lineSegments,
    cta: ctaSegment,
    payoff: { from: payoffStart, duration: endCardFrom - payoffStart + END_CARD_FRAMES },
    endCard: { from: endCardFrom, duration: END_CARD_FRAMES },
  });
}

fs.writeFileSync(path.join(audioDir, "timelines.json"), JSON.stringify(timelines, null, 2));

const tsOut = path.resolve(__dirname, "../src/reelTimelines.ts");
const ts = `// Auto-generated by build-reel-timeline.mjs — do not edit by hand
export type ReelTimeline = {
  id: string;
  fps: number;
  width: number;
  height: number;
  totalFrames: number;
  totalSeconds: number;
  leadIn: number;
  lines: { file: string; text: string; from: number; duration: number }[];
  cta: { file: string; text: string; from: number; duration: number };
  payoff: { from: number; duration: number };
  endCard: { from: number; duration: number };
};

export const REEL_TIMELINES: ReelTimeline[] = ${JSON.stringify(timelines, null, 2)};
`;
fs.writeFileSync(tsOut, ts);

